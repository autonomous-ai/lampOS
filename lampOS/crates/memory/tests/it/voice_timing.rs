//! Synthetic host comparison, not lamp qualification. Run alone in release:
//! `RUST_TEST_THREADS=1 cargo test -p lamp-memory --release --offline --locked --test it voice_timing:: -- --ignored --nocapture`
use lamp_gemini::ToolCall;
use lamp_memory::{Options, Server, days::Days, server::Stopper, store::Day};
use lamp_voice::remember::{DaysClient, RECALL};
use serde_json::{Value, json};
use std::{
    fs, io,
    os::unix::fs::DirBuilderExt,
    path::PathBuf,
    sync::{
        Arc,
        atomic::{AtomicU64, Ordering},
    },
    thread::{self, JoinHandle},
    time::{Duration, Instant, SystemTime, UNIX_EPOCH},
};

const DAY: u64 = 86_400_000;
const REPEATED: usize = 50;
const NOTE_BUDGET: Duration = Duration::from_millis(300);
const CALL_BUDGET: Duration = Duration::from_millis(1_500);
const HOST_SLACK: Duration = Duration::from_millis(100);
const WAIT: Duration = Duration::from_secs(5);
const QUERY: &str = "orchid";
const TARGET_ID: u64 = 12 * 200 + 74;
const TARGET_SAID: &str = "the synthetic orchid belongs in the blue pot";

struct Scratch(PathBuf);

impl Scratch {
    fn new(case: &str) -> Self {
        let path = PathBuf::from(format!("/tmp/lm-vt-{}-{case}", std::process::id()));
        fs::DirBuilder::new().mode(0o700).create(&path).unwrap();
        Self(path)
    }

    fn fixture(&self, now: u64) -> Options {
        let person = self.0.join("store/everyone");
        fs::DirBuilder::new()
            .recursive(true)
            .mode(0o700)
            .create(&person)
            .unwrap();
        let today = now / DAY * DAY;
        let mut id = 0;
        for day in 0..30 {
            let at = today - (29 - day) * DAY;
            let mut lines = String::new();
            for n in 0..200 {
                id += 1;
                let (heard, said) = if id == TARGET_ID {
                    (
                        "what did we say about the synthetic orchid".into(),
                        TARGET_SAID.into(),
                    )
                } else {
                    (
                        format!("synthetic coffee conversation for day {day} entry {n}"),
                        format!("synthetic answer about coffee for day {day} entry {n}"),
                    )
                };
                lines.push_str(&format!(
                    "{}\n",
                    json!({"id":id,"at_unix_ms":at,"heard":heard,"said":said})
                ));
            }
            let date = Day::of(at, 0).unwrap();
            fs::write(person.join(format!("journal-{date}.jsonl")), lines).unwrap();
        }
        let mut kept = String::new();
        for n in 0..200 {
            id += 1;
            kept.push_str(&format!(
                "{}\n",
                json!({"id":id,"at_unix_ms":now,"text":format!("synthetic preference {n:03}: takes coffee black")})
            ));
        }
        fs::write(person.join("kept.jsonl"), kept).unwrap();
        Options {
            dir: self.0.join("store"),
            keep_days: 30,
            local: lamp_memory::store::LocalTime::Offset(0),
        }
    }
}

impl Drop for Scratch {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

struct Running {
    socket: PathBuf,
    stop: Stopper,
    worker: Option<JoinHandle<io::Result<()>>>,
    closes: Arc<AtomicU64>,
}

impl Running {
    fn start(scratch: &Scratch, case: &str, now: u64) -> Self {
        let options = scratch.fixture(now);
        let started = Instant::now();
        let mut store = Days::open(options, now).unwrap();
        let elapsed = started.elapsed();
        let status = store.status(None).unwrap();
        assert_eq!(status.len(), 1);
        assert_eq!((status[0].exchanges, status[0].kept), (6_000, 200));
        emit(
            json!({"measurement":"store_initialization","case":case,"ns":elapsed.as_nanos(),"boundary":"Days::open including JSONL import and durability; excludes fixture creation, count validation and server startup"}),
        );
        let socket = scratch.0.join("m.sock");
        let server = Server::bind(&socket).unwrap();
        let stop = server.stopper();
        let closes = Arc::new(AtomicU64::new(0));
        let trace = Arc::clone(&closes);
        let worker = thread::spawn(move || {
            server.run(&mut store, &mut || now, &mut |line| {
                if line.starts_with("session_close ") {
                    trace.fetch_add(1, Ordering::Relaxed);
                }
            })
        });
        let running = Self {
            socket,
            stop,
            worker: Some(worker),
            closes,
        };
        let until = Instant::now() + WAIT;
        while !scratch.0.join("ready").exists() {
            assert!(Instant::now() < until, "Memory did not become ready");
            thread::sleep(Duration::from_millis(1));
        }
        running
    }

    fn wait_for_closes(&self, expected: u64) {
        // Outside every sample: drain cleanup generated by session renewal
        // before stopping this case's server or starting another case.
        let until = Instant::now() + WAIT;
        while self.closes.load(Ordering::Relaxed) < expected {
            assert!(Instant::now() < until, "session cleanup did not finish");
            thread::sleep(Duration::from_millis(1));
        }
    }

    fn finish(mut self) {
        self.stop.stop();
        self.worker.take().unwrap().join().unwrap().unwrap();
    }
}

impl Drop for Running {
    fn drop(&mut self) {
        if let Some(worker) = self.worker.take() {
            self.stop.stop();
            let _ = worker.join();
        }
    }
}

fn emit(mut record: Value) {
    record["os"] = json!(std::env::consts::OS);
    record["arch"] = json!(std::env::consts::ARCH);
    record["build"] = json!(if cfg!(debug_assertions) {
        "debug"
    } else {
        "release"
    });
    println!("{record}");
}

fn measure(mut record: Value, budget: Duration, mut sample: impl FnMut() -> (Duration, Value)) {
    let (first, details) = sample();
    let repeated: Vec<_> = (0..REPEATED).map(|_| sample().0.as_nanos()).collect();
    let mut ordered = repeated.clone();
    ordered.sort_unstable();
    let percentile = |p: usize| ordered[(REPEATED * p).div_ceil(100) - 1];
    let maximum = ordered[REPEATED - 1];
    record["first_ns"] = json!(first.as_nanos());
    record["first_result"] = details;
    record["repeated"] = json!(REPEATED);
    record["repeated_ns"] = json!(repeated);
    record["p50_ns"] = json!(percentile(50));
    record["p95_ns"] = json!(percentile(95));
    record["p99_ns"] = json!(percentile(99));
    record["max_ns"] = json!(maximum);
    record["target_ns"] = json!(budget.as_nanos());
    record["first_within_target"] = json!(first <= budget);
    record["all_repeated_within_target"] = json!(maximum <= budget.as_nanos());
    record["host_assertion_slack_ns"] = json!(HOST_SLACK.as_nanos());
    emit(record);
    // Correctness is asserted separately by each sample. The exact targets
    // above remain visible even if host scheduling consumes this allowance.
    assert!(
        first <= budget + HOST_SLACK,
        "first call exceeded host allowance"
    );
    assert!(
        maximum <= (budget + HOST_SLACK).as_nanos(),
        "a repeated call exceeded host allowance"
    );
}

#[test]
#[ignore = "release host measurement; run alone, not during builds"]
fn legacy_and_days_voice_requests_over_matched_synthetic_stores() {
    if cfg!(debug_assertions) {
        panic!("run this measurement with --release");
    }
    let now = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap()
        .as_millis() as u64;
    emit(json!({
        "measurement":"context","fixture_now_unix_ms":now,
        "available_parallelism":thread::available_parallelism().map(|n| n.get()).unwrap_or(1),
        "backend":"Days for every case, matching the already-enabled store with old versus new Voice requests; no health reporter",
        "corpus":"fresh identical synthetic 30 UTC calendar days, 6000 exchanges, 200 kept per case; 200 exchanges at midnight per day; one distinctive orchid exchange 17 UTC days before today",
        "first":"first measured operation after fixture creation/import, count validation and server readiness; filesystem caches are not evicted, so this is not a cold-cache measurement",
        "percentiles":"nearest rank over 50 repeated calls only; first call is separate; p99 is the maximum with 50 samples",
        "note_comparison":"legacy kept caps text at 1200 bytes; session_open caps its inner JSON at 1200 bytes, so the selected fact counts may differ",
        "assertions":"all replies must be successful and correct; exact 300 ms/1500 ms target flags are reported separately from a 100 ms host scheduling allowance",
        "excludes":"provider, credentials, model, audio, hardware, clock prompt, instruction assembly and cold filesystem qualification"
    }));
    for case in [
        "legacy_kept",
        "days_session_open",
        "legacy_recall",
        "days_search",
    ] {
        let scratch = Scratch::new(case);
        let running = Running::start(&scratch, case, now);
        let client = if case.starts_with("days_") {
            let started = Instant::now();
            let client = DaysClient::new(running.socket.clone()).unwrap();
            let elapsed = started.elapsed();
            emit(
                json!({"measurement":"voice_client_initialization","case":case,"ns":elapsed.as_nanos(),"boundary":"DaysClient::new including cached timezone read, nonce creation, bounded queue and thread creation; excludes server start and first socket request; thread scheduling need not have completed"}),
            );
            Some(client)
        } else {
            None
        };
        let call = ToolCall {
            id: "synthetic-timing-recall".into(),
            name: RECALL.into(),
            args: json!({"about":QUERY}),
        };
        match case {
            "legacy_kept" => {
                let request = json!({"op":"kept","max_bytes":1200});
                measure(
                    json!({"measurement":"voice_request","case":case,"boundary":"production tools::exchange: connect, serialize/send, full response read, JSON decode and socket drop; excludes legacy kept-text extraction and prompt formatting"}),
                    NOTE_BUDGET,
                    || {
                        let started = Instant::now();
                        let answer =
                            lamp_voice::tools::exchange(&running.socket, &request, NOTE_BUDGET);
                        let elapsed = started.elapsed();
                        let answer = answer.expect("legacy kept did not answer");
                        assert_eq!(answer["ok"], true);
                        let entries = answer["entries"].as_array().unwrap();
                        assert!(!entries.is_empty());
                        for entry in entries {
                            assert!((6001..=6200).contains(&entry["id"].as_u64().unwrap()));
                            assert!(
                                entry["text"]
                                    .as_str()
                                    .unwrap()
                                    .starts_with("synthetic preference ")
                            );
                        }
                        (
                            elapsed,
                            json!({"records":entries.len(),"response_json_bytes":answer.to_string().len()}),
                        )
                    },
                );
            }
            "days_session_open" => {
                let mut session = 0;
                measure(
                    json!({"measurement":"voice_request","case":case,"boundary":"production DaysClient::open_session through return: request building, nonblocking socket, JSON decode, snapshot validation and provenance bookkeeping; new unique session every call; prior session cleanup can overlap; excludes client initialization and prompt formatting"}),
                    NOTE_BUDGET,
                    || {
                        session += 1;
                        let started = Instant::now();
                        let answer = client.as_ref().unwrap().open_session(session, NOTE_BUDGET);
                        let elapsed = started.elapsed();
                        let answer = answer.expect("Days note did not answer within its budget");
                        assert_eq!(answer["invalidated"], false);
                        let note = answer["note"].as_str().unwrap();
                        assert!(note.len() <= 1200);
                        let note: Value = serde_json::from_str(note).unwrap();
                        assert_eq!(note["untrusted"], true);
                        let facts = note["facts"].as_array().unwrap();
                        assert!(!facts.is_empty());
                        assert_eq!(answer["source_ids"].as_array().unwrap().len(), facts.len());
                        for fact in facts {
                            assert!((6001..=6200).contains(&fact["id"].as_u64().unwrap()));
                            assert!(
                                fact["text"]
                                    .as_str()
                                    .unwrap()
                                    .starts_with("synthetic preference ")
                            );
                        }
                        (
                            elapsed,
                            json!({"records":facts.len(),"note_utf8_bytes":answer["note"].as_str().unwrap().len(),"response_json_bytes":answer.to_string().len()}),
                        )
                    },
                );
                running.wait_for_closes(REPEATED as u64);
            }
            "legacy_recall" | "days_search" => {
                measure(
                    json!({"measurement":"voice_request","case":case,"boundary":"production remember::run (legacy) or DaysClient::run (opt-in) through return: time/date lookup, request building, full socket exchange, JSON decoding, answer transformation and provenance where applicable; ToolCall allocation excluded"}),
                    CALL_BUDGET,
                    || {
                        let started = Instant::now();
                        let (answer, ok) = match &client {
                            Some(client) => client.run(&call, CALL_BUDGET),
                            None => lamp_voice::remember::run(&running.socket, &call, CALL_BUDGET),
                        };
                        let elapsed = started.elapsed();
                        assert!(ok, "recall did not return a usable answer: {answer}");
                        let found = answer["found"].as_array().unwrap();
                        assert_eq!(found.len(), 1);
                        assert_eq!(found[0]["you_said"], TARGET_SAID);
                        if client.is_some() {
                            assert_eq!(found[0]["source_id"], TARGET_ID);
                            assert_eq!(answer["untrusted"], true);
                        }
                        (
                            elapsed,
                            json!({"records":found.len(),"response_json_bytes":answer.to_string().len()}),
                        )
                    },
                );
            }
            _ => unreachable!(),
        }
        drop(client);
        running.finish();
    }
}
