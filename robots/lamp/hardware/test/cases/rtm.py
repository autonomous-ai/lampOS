#!/usr/bin/env python3
"""Build the traceability matrix: coverage matrix check -> test case -> script,
limit and evidence -> readiness, and list every gap.

    python3 rtm.py --matrix lampOS/production/matrix-v0.toml          # print it
    python3 rtm.py --matrix ... --out traceability-v0.md               # write it
    python3 rtm.py --matrix ... --check                                # gate only

--check exits 1 when a case file is malformed or a mandatory matrix check has
no case. Gaps that wait on the hardware lead (a limit, a fixture) or on a
script are reported, not failed: they are the work list, not an error.
Standard library only (Python 3.11+, tomllib).
"""
import argparse
import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
GROUPS = ["routine", "station", "integrated", "qualification"]
EXECUTORS = {"selftest", "script", "manual", "script+manual"}
SCRIPT_STATUS = {"ready", "port", "none"}
LIMITS = {"set", "missing"}
REQUIRED = ["id", "title", "group", "order", "checks", "executor", "script_status",
            "pre", "fixture", "agent", "person", "expect", "limit", "evidence",
            "answers", "blocked_by"]


def load(path):
    with open(path, "rb") as f:
        return tomllib.load(f)


def validate(cases):
    errors, seen = [], set()
    for c in cases:
        cid = c.get("id", "?")
        missing = [k for k in REQUIRED if k not in c]
        if missing:
            errors.append(f"{cid}: missing {', '.join(missing)}")
            continue
        if cid in seen:
            errors.append(f"{cid}: duplicate id")
        seen.add(cid)
        if c["group"] not in GROUPS:
            errors.append(f"{cid}: group {c['group']!r} not one of {GROUPS}")
        if c["executor"] not in EXECUTORS:
            errors.append(f"{cid}: executor {c['executor']!r}")
        if c["script_status"] not in SCRIPT_STATUS:
            errors.append(f"{cid}: script_status {c['script_status']!r}")
        if c["limit"] not in LIMITS:
            errors.append(f"{cid}: limit {c['limit']!r}")
        if not c["checks"]:
            errors.append(f"{cid}: covers no check")
        if c["group"] == "qualification" and not any("yes" in p for p in c["pre"]):
            errors.append(f"{cid}: a qualification case needs the person's yes in pre")
    return errors


def ready(c):
    return c["script_status"] == "ready" and c["limit"] != "missing" and not c["blocked_by"]


def cell(items):
    return "<br>".join(items) if items else "—"


def build(matrix, cases, matrix_path):
    checks = matrix.get("check", [])
    ids = [ch["id"] for ch in checks]
    by_check = {i: [] for i in ids}
    new_ids = {}
    for c in cases:
        for i in c["checks"]:
            if i in by_check:
                by_check[i].append(c)
            else:
                new_ids.setdefault(i, []).append(c)

    uncovered = [ch for ch in checks if not by_check[ch["id"]]]
    covered_ready = [i for i in ids if by_check[i] and all(ready(c) for c in by_check[i])]
    mand = [ch for ch in checks if ch.get("mandatory")]
    mand_ready = [ch for ch in mand if ch["id"] in covered_ready]

    out = []
    w = out.append
    w("# Traceability matrix, version 0")
    w("")
    w("Generated by `rtm.py` from the coverage matrix "
      f"(`{matrix_path}`, suite {matrix['suite']['version']}, "
      f"approved = {str(matrix['suite'].get('approved', False)).lower()}) and "
      "`test-cases-v0.toml`. Do not edit by hand: change either file and run it again.")
    w("")
    w("A check is **ready** when every case covering it has a V2 script (or needs none), "
      "a set limit, and nothing blocking it. Every limit is a proposal until the hardware "
      "lead approves the matrix.")
    w("")
    w("## Summary")
    w("")
    w("| | Count |")
    w("|---|---:|")
    w(f"| Matrix checks | {len(checks)} |")
    w(f"| Covered by a case | {len(checks) - len(uncovered)} |")
    w(f"| Ready to run today | {len(covered_ready)} |")
    w(f"| Mandatory checks | {len(mand)} |")
    w(f"| Mandatory and ready | {len(mand_ready)} |")
    per_group = ", ".join("{} {}".format(sum(c["group"] == g for c in cases), g) for g in GROUPS)
    w(f"| Cases | {len(cases)} ({per_group}) |")
    w(f"| Proposed new check ids | {len(new_ids)} |")
    w("")
    w("## Check → case")
    w("")
    w("| Check | Part | Kind | Mandatory | Method | Case | Script | Limit | Ready |")
    w("|---|---|---|---|---|---|---|---|---|")
    for ch in checks:
        cs = by_check[ch["id"]]
        w("| `{}` | {} | {} | {} | {} | {} | {} | {} | {} |".format(
            ch["id"], ch.get("part", ""), ch.get("kind", ""),
            "yes" if ch.get("mandatory") else "no", ch.get("method", ""),
            cell([c["id"] for c in cs]) if cs else "**none**",
            cell([c["script_status"] for c in cs]),
            cell([c["limit"] for c in cs]),
            "yes" if ch["id"] in covered_ready else "no"))
    w("")
    if new_ids:
        w("## Proposed new check ids (not in the matrix yet)")
        w("")
        w("| Id | Case | For the matrix's next version |")
        w("|---|---|---|")
        for i, cs in new_ids.items():
            w(f"| `{i}` | {cell([c['id'] for c in cs])} | {cs[0]['title']} |")
        w("")
    w("## Case → steps, evidence and what blocks it")
    w("")
    w("| Case | Title | Group | Checks | Executor | Script | Evidence | Blocked by |")
    w("|---|---|---|---|---|---|---|---|")
    for c in sorted(cases, key=lambda c: c["order"]):
        w("| {} | {} | {} | {} | {} | {} | {} | {} |".format(
            c["id"], c["title"], c["group"], cell([f"`{i}`" for i in c["checks"]]),
            c["executor"], (f"`{c['script']}` " if c.get("script") else "") + f"({c['script_status']})",
            cell(c["evidence"]), cell(c["blocked_by"])))
    w("")
    w("## Gaps")
    w("")
    gaps = 0
    if uncovered:
        w("**Checks with no case:** " + ", ".join(f"`{ch['id']}`" for ch in uncovered))
        w("")
        gaps += len(uncovered)
    for title, pick in [
        ("Limits not set (the hardware lead's)", lambda c: c["limit"] == "missing"),
        ("Fixtures needed", lambda c: bool(c["fixture"])),
        ("Scripts to port from the V1 bench kit", lambda c: c["script_status"] == "port"),
        ("Scripts to write", lambda c: c["script_status"] == "none"),
    ]:
        hit = [c for c in sorted(cases, key=lambda c: c["order"]) if pick(c)]
        if hit:
            w(f"**{title}** ({len(hit)}):")
            w("")
            for c in hit:
                extra = f": {', '.join(c['fixture'])}" if title.startswith("Fixtures") else ""
                w(f"- {c['id']} {c['title']}{extra}")
            w("")
            gaps += len(hit)
    if not gaps:
        w("None.")
        w("")
    return "\n".join(out), uncovered, mand


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--matrix", required=True, help="the coverage matrix, e.g. lampOS/production/matrix-v0.toml")
    ap.add_argument("--cases", default=str(HERE / "test-cases-v0.toml"))
    ap.add_argument("--matrix-name", help="how the output names the matrix (default: --matrix as given)")
    ap.add_argument("--out", help="write the Markdown here instead of printing it")
    ap.add_argument("--check", action="store_true", help="validate and report only; exit 1 on an error")
    args = ap.parse_args()

    matrix = load(args.matrix)
    cases = load(args.cases).get("case", [])
    errors = validate(cases)
    if errors:
        for e in errors:
            print(f"rtm: {e}", file=sys.stderr)
        sys.exit(1)

    text, uncovered, mand = build(matrix, cases, args.matrix_name or args.matrix)
    mand_uncovered = [ch["id"] for ch in uncovered if ch.get("mandatory")]
    if args.check:
        for i in mand_uncovered:
            print(f"rtm: mandatory check {i} has no case", file=sys.stderr)
        print(f"rtm: {len(cases)} cases, {len(uncovered)} checks uncovered "
              f"({len(mand_uncovered)} mandatory)")
        sys.exit(1 if mand_uncovered else 0)
    if args.out:
        Path(args.out).write_text(text + "\n")
    else:
        print(text)


if __name__ == "__main__":
    main()
